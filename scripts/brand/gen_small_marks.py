"""Generate small Android VectorDrawables from the small Aries SVG (stdlib only).

Usage: python3 scripts/brand/gen_small_marks.py
The ram path stays identical to the original artwork. Opaque gold paths can
overpaint the ram in the two-colour mark; the SVG mask is unnecessary there.
Notification and Wear icons use just the white silhouette, without tiny stars.
Derived artwork is covered by assets/aries/LICENSE.
"""
import argparse
from pathlib import Path
import xml.etree.ElementTree as ET

REPO = Path(__file__).resolve().parents[2]
SVG = "{http://www.w3.org/2000/svg}"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source", type=Path, default=REPO / "assets/aries/aries-mark-small.svg")
parser.add_argument("--res-dir", type=Path, default=REPO / "android/app/src/main/res")
parser.add_argument("--wear-res-dir", type=Path, default=REPO / "android/wear/src/main/res")


def generate(source, res, wear_res):
    svg = ET.parse(source).getroot()
    x, y, width, height = svg.attrib["viewBox"].split()
    ram = svg.find(f"{SVG}g/{SVG}path")
    # Keep the original ram coordinates instead of rounding every curve point.
    ram_path = ram.attrib["d"]

    def vector(ink, constellation, inset=0):
        paths = []
        if constellation:
            for node in svg:
                if node.tag == SVG + "path":
                    if "stroke" in node.attrib:
                        paths.append(f'<path android:pathData="{node.attrib["d"]}" '
                                     f'android:strokeColor="#F4B73A" android:strokeWidth="{node.attrib["stroke-width"]}" '
                                     'android:strokeLineCap="round" android:strokeLineJoin="round" />')
                    else:
                        paths.append(f'<path android:fillColor="#F4B73A" android:pathData="{node.attrib["d"]}" />')
                elif node.tag == SVG + "circle":
                    cx, cy, r = (float(node.attrib[k]) for k in ("cx", "cy", "r"))
                    paths.append(f'<path android:fillColor="#F4B73A" android:pathData="'
                                 f'M{cx-r:g},{cy:g} a{r:g},{r:g} 0,1 0,{2*r:g},0 a{r:g},{r:g} 0,1 0,{-2*r:g},0" />')
        scale = 1 - 2 * inset
        content = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand/gen_small_marks.py; assets/aries/LICENSE applies. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp" android:height="24dp" android:viewportWidth="{width}" android:viewportHeight="{height}">
    <group android:translateX="{float(width)*inset:g}" android:translateY="{float(height)*inset:g}"
        android:scaleX="{scale:g}" android:scaleY="{scale:g}">
        <group android:translateX="{-float(x):g}" android:translateY="{-float(y):g}">
            <group android:translateX="-80" android:translateY="967" android:scaleX="0.22" android:scaleY="-0.22">
                <path android:fillColor="{ink}" android:pathData="{ram_path}" />
            </group>
            {chr(10).join(paths)}
        </group>
    </group>
</vector>
'''
        return "\n".join(line.rstrip() for line in content.splitlines()) + "\n"

    def save(root, name, content):
        destination = root / "drawable" / (name + ".xml")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content)
        # Remove the superseded generated rasters, including density variants.
        for old in root.glob(f"drawable-*/{name}.png"):
            old.unlink()

    save(res, "mark_ink", vector("#2B2724", True))
    save(res, "mark_light", vector("#F3EDE6", True))
    silhouette = vector("#FFFFFF", False, inset=.05)
    save(res, "ic_stat_aries", silhouette)
    save(wear_res, "ic_aries", silhouette)


if __name__ == "__main__":
    args = parser.parse_args()
    generate(args.source, args.res_dir, args.wear_res_dir)
